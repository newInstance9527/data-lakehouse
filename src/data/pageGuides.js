/**
 * 各功能页右上角「说明」
 * 固定四段：模块说明 · 操作说明 · 使用示例 · 下一步可以做什么
 * sections.type: text | list | steps | example | note | kv
 */

import { PAGE_GUIDES_EN } from '@/i18n/pageGuidesEn'
import { PHRASES_EN } from '@/i18n/phrases'

function guide(title, sections) {
  return { title: `${title} · 说明`, sections }
}

/** 四段标准结构 */
function sections4({ about, ops, example, next }) {
  return [
    { heading: '模块说明', type: 'text', content: about },
    { heading: '操作说明', type: 'steps', items: ops },
    typeof example === 'string'
      ? { heading: '使用示例', type: 'example', content: example }
      : { heading: '使用示例', type: 'steps', items: example },
    { heading: '下一步可以做什么', type: 'list', items: next },
  ]
}

