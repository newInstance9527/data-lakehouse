export function pageGuideOf(id, locale = 'zh') {
  const fallback = {
    title: locale === 'en' ? 'Feature guide' : '功能说明',
    sections: [
      {
        heading: locale === 'en' ? 'Note' : '说明',
        type: 'note',
        content:
          locale === 'en' ? 'Guide for this module is not ready yet.' : '本模块说明待补充。',
      },
    ],
  }

  if (locale === 'en') {
    if (PAGE_GUIDES_EN[id]) return PAGE_GUIDES_EN[id]
    const zh = PAGE_GUIDES[id]
    if (zh) return localizeGuideShallow(zh)
  }

  return PAGE_GUIDES[id] || fallback
}

function localizeGuideShallow(guideObj) {
  if (!guideObj) return guideObj
  return {
    ...guideObj,
    title: String(guideObj.title || '')
      .replace(/ · 说明$/, ' · Guide')
      .replace(/^功能说明$/, 'Feature guide'),
    sections: (guideObj.sections || []).map((sec) => ({
      ...sec,
      heading: PHRASES_EN[sec.heading] || sec.heading,
      items: Array.isArray(sec.items)
        ? sec.items.map((it) => {
            if (it && typeof it === 'object' && 'label' in it) {
              return { ...it, label: PHRASES_EN[it.label] || it.label }
            }
            return it
          })
        : sec.items,
    })),
  }
}

export function normalizeGuide(guideObj) {
  if (!guideObj) return { title: '功能说明', sections: [] }
  if (typeof guideObj === 'string') {
    return {
      title: '功能说明',
      sections: [{ heading: '', type: 'text', content: guideObj }],
    }
  }
  if (Array.isArray(guideObj)) {
    return {
      title: '功能说明',
      sections: [{ heading: '', type: 'text', content: guideObj }],
    }
  }
  if (guideObj.body && !guideObj.sections) {
    return {
      title: guideObj.title || '功能说明',
      sections: [{ heading: '', type: 'text', content: guideObj.body }],
    }
  }
  return {
    title: guideObj.title || '功能说明',
    sections: Array.isArray(guideObj.sections) ? guideObj.sections : [],
  }
}
