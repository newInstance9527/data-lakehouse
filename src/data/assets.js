export function findAsset(idOrKey) {
  const q = String(idOrKey ?? '').trim()
  if (!q) return null
  return (
    ASSET_DATA.find((a) => a.id === q || a.key === q || a.name === q) ||
    ASSET_DATA.find((a) => a.key.endsWith('.' + q) || a.key.includes(q)) ||
    null
  )
}
