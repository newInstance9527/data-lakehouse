/** 类型在分类内的展示顺序（与 DS_CAT_MAP 声明顺序一致） */
const DS_TYPE_ORDER = Object.keys(DS_CAT_MAP)

export function typeCategoryKey(type) {
  if (DS_CAT_MAP[type]) return DS_CAT_MAP[type]
  if (String(type).includes('API')) return 'api'
  return 'other'
}

function catRank(cat) {
  const i = DS_CAT_OPTIONS.findIndex((c) => c.value === cat)
  return i >= 0 ? i : DS_CAT_OPTIONS.length
}

function typeRank(type) {
  const i = DS_TYPE_ORDER.indexOf(type)
  return i >= 0 ? i : DS_TYPE_ORDER.length
}

/** 按分类顺序 + 分类内声明顺序排序类型名 */
export function sortTypesByCategory(types) {
  return [...types].sort((a, b) => {
    const d = catRank(typeCategoryKey(a)) - catRank(typeCategoryKey(b))
    if (d !== 0) return d
    const t = typeRank(a) - typeRank(b)
    if (t !== 0) return t
    return String(a).localeCompare(String(b), 'zh')
  })
}

/**
 * 将类型列表按分类分组（用于 select optgroup）
 * @param {string[]|{value:string,count?:number}[]} types
 * @returns {{value:string,label:string,types:{value:string,count?:number}[]}[]}
 */
export function groupTypesByCategory(types) {
  const normalized = types.map((t) =>
    typeof t === 'string' ? { value: t } : { value: t.value, count: t.count },
  )
  const ordered = sortTypesByCategory(normalized.map((t) => t.value))
  const byValue = Object.fromEntries(normalized.map((t) => [t.value, t]))
  const groups = []
  const seen = new Set()

  for (const cat of DS_CAT_OPTIONS) {
    const items = ordered
      .filter((name) => typeCategoryKey(name) === cat.value)
      .map((name) => byValue[name])
    if (!items.length) continue
    items.forEach((t) => seen.add(t.value))
    groups.push({ value: cat.value, label: cat.label, types: items })
  }

  const rest = ordered.filter((name) => !seen.has(name)).map((name) => byValue[name])
  if (rest.length) {
    groups.push({ value: 'other', label: '其他', types: rest })
  }
  return groups
}

